CREATE TABLE diagram_edit_plan (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    change_run_id BIGINT NOT NULL,
    change_item_id BIGINT NOT NULL,
    baseline_document_id BIGINT NULL,
    analysis_mode VARCHAR(16) NOT NULL DEFAULT 'TEST_ONLY',
    plan_status VARCHAR(32) NOT NULL,
    automatic_edit_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    relation_status VARCHAR(24) NOT NULL DEFAULT 'REVIEW_REQUIRED',
    target_process_code VARCHAR(32) NULL,
    target_sheet_name VARCHAR(128) NULL,
    target_filename VARCHAR(255) NULL,
    requested_scenario_json LONGTEXT NULL,
    plan_json LONGTEXT NOT NULL,
    review_required_json LONGTEXT NOT NULL,
    output_filename VARCHAR(255) NULL,
    output_sha256 CHAR(64) NULL,
    output_content LONGBLOB NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_diagram_edit_plan_run FOREIGN KEY (change_run_id) REFERENCES change_run(id),
    CONSTRAINT fk_diagram_edit_plan_item FOREIGN KEY (change_item_id) REFERENCES change_item(id),
    CONSTRAINT fk_diagram_edit_plan_document FOREIGN KEY (baseline_document_id) REFERENCES baseline_document(id),
    CONSTRAINT ck_diagram_edit_plan_mode CHECK (analysis_mode = 'TEST_ONLY'),
    CONSTRAINT ck_diagram_edit_plan_relation CHECK (relation_status = 'REVIEW_REQUIRED'),
    KEY idx_diagram_edit_plan_run (change_run_id, change_item_id),
    KEY idx_diagram_edit_plan_status (plan_status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
