CREATE TABLE balance_evidence_review_route (
    id BIGINT NOT NULL AUTO_INCREMENT,
    snapshot_id CHAR(64) NOT NULL,
    candidate_id VARCHAR(96) NOT NULL,
    case_key VARCHAR(128) NOT NULL,
    review_history_id BIGINT NOT NULL,
    review_version BIGINT NOT NULL,
    route_id VARCHAR(128) NOT NULL,
    source_equipment VARCHAR(128) NULL,
    target_equipment VARCHAR(128) NULL,
    movement_type VARCHAR(32) NULL,
    direction_confirmed BOOLEAN NULL,
    material_type VARCHAR(128) NULL,
    quantity DECIMAL(24,8) NULL,
    unit VARCHAR(64) NULL,
    period VARCHAR(128) NULL,
    quantity_evidence_reference VARCHAR(512) NULL,
    baseline_time_reference VARCHAR(512) NULL,
    path_evidence_reference VARCHAR(512) NULL,
    path_description TEXT NULL,
    branch_merge_type VARCHAR(32) NULL,
    recycle_path_id VARCHAR(128) NULL,
    boundary_scope_id VARCHAR(128) NULL,
    topology_confirmed BOOLEAN NULL,
    scope_expected_route_count INT NULL,
    scope_all_inflows BOOLEAN NULL,
    scope_all_outflows BOOLEAN NULL,
    scope_branches_merges BOOLEAN NULL,
    scope_internal_recycles BOOLEAN NULL,
    scope_interprocess_moves BOOLEAN NULL,
    scope_external_boundaries BOOLEAN NULL,
    scope_generation_consumption BOOLEAN NULL,
    scope_unit_period BOOLEAN NULL,
    scope_baseline_time BOOLEAN NULL,
    route_review_state VARCHAR(32) NOT NULL,
    upload_sha256 CHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_step7_route_version (snapshot_id, candidate_id, route_id, review_version),
    KEY idx_step7_route_scope (snapshot_id, boundary_scope_id, route_review_state),
    KEY idx_step7_route_history (case_key, review_history_id),
    CONSTRAINT fk_step7_route_candidate FOREIGN KEY (snapshot_id, candidate_id)
        REFERENCES balance_evidence_review_candidate(snapshot_id, candidate_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE balance_evidence_provenance_history (
    id BIGINT NOT NULL AUTO_INCREMENT,
    snapshot_id CHAR(64) NOT NULL,
    candidate_id VARCHAR(96) NOT NULL,
    case_key VARCHAR(128) NOT NULL,
    review_history_id BIGINT NOT NULL,
    review_version BIGINT NOT NULL,
    route_id VARCHAR(128) NOT NULL DEFAULT '',
    evidence_type VARCHAR(48) NOT NULL,
    evidence_reference VARCHAR(512) NOT NULL,
    evidence_location VARCHAR(512) NOT NULL,
    verification_method VARCHAR(128) NOT NULL,
    verified_by VARCHAR(128) NOT NULL,
    verified_at DATETIME NULL,
    verification_comment TEXT NOT NULL,
    provenance_state VARCHAR(32) NOT NULL,
    upload_sha256 CHAR(64) NOT NULL,
    event_sha256 CHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_step7_evidence_event (event_sha256),
    KEY idx_step7_evidence_review (snapshot_id, candidate_id, review_version),
    KEY idx_step7_evidence_route (snapshot_id, route_id),
    CONSTRAINT fk_step7_provenance_candidate FOREIGN KEY (snapshot_id, candidate_id)
        REFERENCES balance_evidence_review_candidate(snapshot_id, candidate_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
